"""Generate docs/demo/data.js: the determinism scenarios of tests/run_tests.py, each
step's request and response, and the board before each step, for docs/demo/index.html.

    python3 tools/demo_data.py --binary build/typmax-router
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "tests"))
from router_client import RouterClient  # noqa: E402
from run_tests import determinism_requests  # noqa: E402

BLURB = {
    "walkaround": "Net A must cross net B's big pad. Walkaround (the default) goes round; "
                  "mark_obstacles refuses with `collision`; `step` feeds the cursor like a mouse.",
    "shove": "Net A's straight line is blocked by three tracks of net C. Shove pushes them aside: "
             "each moved track is a remove plus an add. Then apply, and route again: nothing left to do.",
    "shove_drag": "Drag one of C's segments up with the push-and-shove dragger, then down with walkaround.",
    "via": "U1.1 is on F.Cu, U2.1 on B.Cu. A via waypoint drops to the back layer.",
    "unroutable": "U2.1 sits inside a closed ring of net B and a keepout: `unroutable`, in both modes.",
    "power": "VCC is in the Power class: wider track, larger clearance from net D's track.",
    "holes": "Net E skirts a non-plated mounting hole; net A goes from a through-hole pad to the back.",
    "arc": "Walkaround past an arc track of net B.",
    "arc_shove": "The same board, shove mode: the arc is pushed.",
}


def apply_proposal(board, proposal):
    rm = set(proposal["remove"])
    nb = json.loads(json.dumps(board))
    nb["tracks"] = [t for t in nb["tracks"] if t["id"] not in rm]
    nb["vias"] = [v for v in nb["vias"] if v["id"] not in rm]
    for a in proposal["add"]:
        item = {k: v for k, v in a.items() if k != "kind"}
        (nb["tracks"] if a["kind"] == "track" else nb["vias"]).append(item)
    return nb


def run(binary):
    scenarios = []
    for name, steps in determinism_requests():
        board_file = name.split("_")[0] if name != "shove_drag" else "shove"
        board = json.loads((ROOT / "tests" / "boards" / f"{board_file}.json").read_text())
        out = {"name": name, "board_file": board_file, "blurb": BLURB.get(name, ""), "steps": []}
        with RouterClient(binary) as c:
            c.call("load_board", {"board": board})
            last = None
            revision = 0
            for method, params in steps:
                if method == "apply_last":
                    params = {"proposal": last, "base_revision": revision}
                    method = "apply"
                resp = c.request(method, params)
                out["steps"].append({"method": method, "params": params, "board": board, "response": resp})
                if resp["ok"] and method in ("route", "drag"):
                    last = resp["result"]["proposal"]
                if resp["ok"] and method == "apply":
                    revision = resp["result"]["revision"]
                    board = apply_proposal(board, params["proposal"])
        scenarios.append(out)
    return scenarios


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", default=str(ROOT / "build" / "typmax-router"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "demo" / "data.js"))
    a = ap.parse_args()
    data = run(a.binary)
    pathlib.Path(a.out).write_text("// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: 2026 The typmax-router authors\n"
                               "// generated by tools/demo_data.py; do not edit\n"
                               "window.DEMO_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"{a.out}: {len(data)} scenarios, {sum(len(s['steps']) for s in data)} steps")


if __name__ == "__main__":
    main()
